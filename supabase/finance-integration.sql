--
-- هذا ملف تكامل فقط: ما يغيّر جدول الطلبات ولا الأسعار ولا منطق الشراء.
-- يضيف: حالة مزامنة مالية على الطلب · سجل محاولات · حالة آخر مزامنة كتالوك.
--
-- المنطق المالي (10/10/80 · Transactions · Subscriptions) يبقى كله في
