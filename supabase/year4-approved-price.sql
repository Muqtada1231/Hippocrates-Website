-- =============================================================================
-- HIPPOCRATES — التعريف المعتمد لبكج المرحلة الرابعة (year4)
--
-- المعتمد:
--   القيمة المفردة : 185,000
--   سعر البيع      : 130,000  (وفر 55,000 ≈ 29.73%)
--   التوزيع        : 21,000 + 17,500×4 + 14,000 + 14,000 + 11,000 = 130,000
--
-- المحتوى (8 كورسات) ما ينلمس — موجود وصحيح أصلاً.
-- السعر كان 125,000 والتوزيع كان مجموعه 125,000؛ نرفع الاثنين معاً حتى
-- يبقى مجموع التوزيع مساوياً لسعر البيع، وإلا ضاعت 5,000 من كل عملية بيع
-- عند تقسيم الإيراد.
--
-- كل أمر مقيّد بقيمته القديمة، فالملف آمن لإعادة التشغيل وما يمس صفاً ثانياً.
-- =============================================================================

begin;

-- 1) سعر البيع: 125,000 → 130,000
update public.packages
   set price = 130000
 where key   = 'year4'
   and price = 125000;

-- 2) الصفّان الوحيدان المختلفان عن التوزيع المعتمد
update public.package_courses
   set allocation = 14000
 where package_id = 'year4' and course_id = 'clin-med'  and allocation = 10000;

update public.package_courses
   set allocation = 11000
 where package_id = 'year4' and course_id = 'clin-surg' and allocation = 10000;

commit;
